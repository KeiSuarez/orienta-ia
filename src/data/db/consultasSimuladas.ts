const COLUMNAS = ['tramite_detectado', 'resultado', 'condicion', 'tipo_entidad', 'entidad', 'provincia', 'rango_edad'] as const;

/** Devuelve las 2.000 consultas simuladas decodificadas. */
export function cargarConsultasSimuladas(): EventoConsulta[] {
  const base = new Date(`${FECHA_BASE}T12:00:00Z`).getTime();
  const texto = DATOS.join('');
  const eventos: EventoConsulta[] = [];

  for (let i = 0; i + 9 <= texto.length; i += 9) {
    const registro = texto.slice(i, i + 9);
    const dias = parseInt(registro.slice(0, 2), 36);
    const fecha = new Date(base + dias * 86400000).toISOString().split('T')[0];
    const valor = (col: number) => VALORES[COLUMNAS[col]][parseInt(registro[2 + col], 36)] as string;

    eventos.push({
      fecha,
      tramite_detectado: valor(0),
      resultado: valor(1) as ResultadoConsulta,
      condicion: valor(2),
      tipo_entidad: valor(3),
      entidad: valor(4),
      provincia: valor(5),
      rango_edad: valor(6),
      mes: fecha.slice(0, 7)
    });
  }
  return eventos;
}